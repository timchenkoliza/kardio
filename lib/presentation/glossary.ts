/**
 * English → Russian clinical glossary for the physician presentation layer.
 * It names what a publication is about (topics, populations, drug classes); it
 * never states what a publication found. Order matters: the most specific term
 * wins and suppresses the generic one it contains.
 */

export interface GlossaryEntry {
  /** Russian label shown to the physician (lowercase unless an abbreviation). */
  ru: string;
  pattern: RegExp;
  /** Labels this entry makes redundant (e.g. «лёгочная гипертензия» suppresses «артериальная гипертензия»). */
  suppresses?: readonly string[];
  /** Population/context tags read after the subject. */
  population?: boolean;
  /** How the population reads at the end of a title («у взрослых», «при беременности»). */
  phrase?: string;
  /** What the document does with the subject (prevention, treatment, diagnosis…), read after a dash. */
  aspect?: boolean;
}

