export function pharmaFormatLabel(format: PharmaCommercialFormat): string {
  return PHARMA_KP_FORMATS.find(value => value.id === format)?.label ?? format;
}

export interface ProfessionalAgentTemplate {
  id: string;
  kind: ProfessionalAgentKind;
  family: ProfessionalAgentFamily;
  availability: ProfessionalAgentAvailability;
  title: string;
  description: string;
  instruction: string;
  cadence: ProfessionalAgentCadence;
  outputFormat: ProfessionalAgentOutput;
  topics: string[];
  commercial: boolean;
  sponsorName: string | null;
  commercialFormat: PharmaCommercialFormat | null;
}

type IndependentTemplate = Omit<ProfessionalAgentTemplate, "commercial" | "sponsorName" | "commercialFormat">;
type PartnerTemplate = Omit<ProfessionalAgentTemplate, "family" | "availability" | "commercial" | "sponsorName" | "commercialFormat"> & { commercialFormat: PharmaCommercialFormat };

function independent(value: IndependentTemplate): ProfessionalAgentTemplate {
  return { ...value, commercial: false, sponsorName: null, commercialFormat: null };
}

function partner(value: PartnerTemplate): ProfessionalAgentTemplate {
  return {
    ...value,
    family: "partner",
    availability: "ready",
    commercial: true,
    sponsorName: "Синтетический партнёр",
  };
}

